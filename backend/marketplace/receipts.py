def receipt_available(order) -> bool:
    """Receipts exist once the payment is confirmed and the order wasn't cancelled."""
    return order.status in RECEIPT_STATUSES


def _money(value) -> str:
    return f"{Decimal(value):,.0f}".replace(",", " ")


def _name(user) -> str:
    return user.full_name or user.username


def _lines(order, viewer_is_seller: bool, t: dict) -> list:
    """(label, qty, amount, bold) rows for the table."""
    breakdown = order.price_breakdown if isinstance(order.price_breakdown, dict) else {}
    price = Decimal(breakdown.get("price_xaf") or (order.amount_xaf - order.delivery_fee_xaf))
    rows = [(f"{order.listing.title} ({order.variant_label})" if order.variant_label else order.listing.title, str(order.quantity or 1), price, False)]
    if order.discount_xaf:
        code = breakdown.get("coupon_code", "")
        rows.append((f"{t['discount']} {code}".strip(), "", -Decimal(order.discount_xaf), False))
    if order.delivery_fee_xaf:
        rows.append((t["delivery_fee"], "", Decimal(order.delivery_fee_xaf), False))
    if order.deposit_xaf:
        rows.append((t["deposit"], "", Decimal(order.deposit_xaf), False))
    rows.append((t["total_paid"], "", Decimal(order.amount_xaf) + Decimal(order.deposit_xaf), True))
    escrow = getattr(order.booking, "escrow", None)
    if viewer_is_seller and escrow is not None and escrow.status in ("RELEASED", "REFUNDED"):
        if escrow.refunded_amount_xaf:
            rows.append((t["refunded"], "", -Decimal(escrow.refunded_amount_xaf), False))
        rows.append((t["fee"], "", -Decimal(escrow.platform_fee_xaf), False))
        rows.append((t["net"], "", Decimal(escrow.payee_amount_xaf), True))
    return rows


def _wrap(draw, text: str, font, width: float) -> list:
    lines, current = [], ""
    for word in text.split():
        candidate = f"{current} {word}".strip()
        if current and draw.textlength(candidate, font=font) > width:
            lines.append(current)
            current = word
        else:
            current = candidate
    return lines + [current] if current else lines or [""]


def render_receipt_image(order, viewer, lang: str = "en") -> Image.Image:
    t = TEXT["fr" if lang == "fr" else "en"]
    viewer_is_seller = viewer.id == order.listing.lister_user_id
    image = Image.new("RGB", PAGE, "white")
    draw = ImageDraw.Draw(image)
    width = PAGE[0] - 2 * MARGIN
    right = PAGE[0] - MARGIN

    draw.text((MARGIN, MARGIN), "OAZILAND", font=_font("sans", True, 54), fill=NAVY)
    title = t["statement"] if viewer_is_seller else t["receipt"]
    draw.text((right, MARGIN + 6), title, font=_font("sans", True, 40), fill=SLATE, anchor="ra")
    y = MARGIN + 90
    draw.line((MARGIN, y, right, y), fill=NAVY, width=4)
    y += 35

    local = timezone.localtime(order.created_at)
    meta = [
        (t["order"], f"#{str(order.pk)[:8].upper()}"),
        (t["date"], local.strftime("%d/%m/%Y %H:%M")),
        (t["status"], t.get(order.status, order.status)),
    ]
    label_font, value_font = _font("sans", False, 28), _font("sans", True, 30)
    for label, value in meta:
        draw.text((MARGIN, y), label, font=label_font, fill=SLATE)
        draw.text((MARGIN + 260, y), value, font=value_font, fill=NAVY)
        y += 46
    y += 20
    for label, person in ((t["seller"], order.listing.lister_user), (t["buyer"], order.buyer)):
        draw.text((MARGIN, y), label, font=label_font, fill=SLATE)
        draw.text((MARGIN + 260, y), _name(person), font=value_font, fill=NAVY)
        y += 46
    y += 30

    # Table header
    qty_x, amount_x = MARGIN + int(width * 0.62), right
    head = _font("sans", True, 26)
    draw.rectangle((MARGIN, y, right, y + 52), fill=LIGHT)
    draw.text((MARGIN + 16, y + 10), t["item"], font=head, fill=NAVY)
    draw.text((qty_x, y + 10), t["qty"], font=head, fill=NAVY)
    draw.text((amount_x - 16, y + 10), t["amount"], font=head, fill=NAVY, anchor="ra")
    y += 52
    for label, qty, amount, bold in _lines(order, viewer_is_seller, t):
        font = _font("sans", bold, 30)
        wrapped = _wrap(draw, label, font, qty_x - MARGIN - 40)
        row_h = 46 * len(wrapped) + 14
        if bold:
            draw.line((MARGIN, y, right, y), fill=SLATE, width=2)
        for i, part in enumerate(wrapped):
            draw.text((MARGIN + 16, y + 10 + 46 * i), part, font=font, fill=NAVY if bold else "#0F172A")
        draw.text((qty_x, y + 10), qty, font=font, fill="#0F172A")
        colour = GREEN if bold and amount > 0 and label == t["net"] else NAVY if bold else "#0F172A"
        text = f"-{_money(abs(amount))}" if amount < 0 else _money(amount)
        draw.text((amount_x - 16, y + 10), text, font=font, fill=colour, anchor="ra")
        y += row_h
        draw.line((MARGIN, y, right, y), fill=LIGHT, width=2)
    y += 40

    notes = []
    if order.delivery_method:
        method = t["pickup"] if order.delivery_method == "PICKUP" else t[order.delivery_method]
        notes.append(f"{t['delivery']}: {method}" + (f" - {order.delivery_address}" if order.delivery_address else ""))
    if order.courier_name or order.tracking_number:
        notes.append(f"{t['tracking']}: {' '.join(filter(None, [order.courier_name, order.tracking_number]))}")
    if order.rental_starts_on and order.rental_ends_on:
        notes.append(f"{t['rental']}: {order.rental_starts_on:%d/%m/%Y} - {order.rental_ends_on:%d/%m/%Y}")
    notes.append(t["escrow"])
    note_font = _font("sans", False, 26)
    for note in notes:
        for part in _wrap(draw, note, note_font, width):
            draw.text((MARGIN, y), part, font=note_font, fill=SLATE)
            y += 38
        y += 8

    footer = f"{t['generated']} {timezone.localtime().strftime('%d/%m/%Y %H:%M')}  ·  #{str(order.pk).upper()}"
    draw.text((MARGIN, PAGE[1] - MARGIN), footer, font=_font("sans", False, 22), fill=SLATE, anchor="ld")
    return image


def render_receipt_pdf(order, viewer, lang: str = "en") -> bytes:
    buffer = io.BytesIO()
    render_receipt_image(order, viewer, lang).save(
        buffer, format="PDF", resolution=150.0, title=f"Oaziland order {str(order.pk)[:8].upper()}", author="Oaziland",
    )
    return buffer.getvalue()
